"""Renders an AnalysisResult as a human-readable Markdown report."""

from __future__ import annotations

from app.domain.models import AnalysisResult, BasicEvent, Gate


def _render_node(node: Gate | BasicEvent, depth: int = 0) -> list[str]:
    indent = "  " * depth
    lines: list[str] = []
    if isinstance(node, BasicEvent):
        prob = f"{node.probability:.4f}" if node.probability is not None else "unknown"
        lines.append(f"{indent}- **[BASIC]** {node.description} (id: `{node.id}`, p = {prob})")
        if node.rationale:
            lines.append(f"{indent}  - _{node.rationale}_")
    else:
        lines.append(f"{indent}- **[{node.gate_type}]** {node.description} (id: `{node.id}`)")
        for child in node.children:
            lines.extend(_render_node(child, depth + 1))
    return lines


def _fmt_prob(p: float | None) -> str:
    return f"{p:.4%}" if p is not None else "unavailable"


def _fmt_money(amount: float | None, currency: str) -> str:
    return f"{amount:,.2f} {currency}" if amount is not None else "unavailable"


def render_markdown_report(result: AnalysisResult) -> str:
    lines: list[str] = [f"# Fault Tree Analysis: {result.top_event.description}", ""]
    lines.append(f"- Analysis ID: `{result.analysis_id}`")
    if result.provider:
        lines.append(f"- Generated by: {result.provider} ({result.model})")
    lines.append(f"- Created: {result.created_at}")
    lines.append(f"- Updated: {result.updated_at}")
    lines.append("")

    lines.append("## Fault Tree")
    lines.append("")
    lines.extend(_render_node(result.fault_tree.root))
    lines.append("")

    lines.append("## Top Event Probability")
    lines.append("")
    lines.append(
        f"- Baseline: {_fmt_prob(result.baseline_probability.top_event_probability)} "
        f"({result.baseline_probability.method})"
    )
    lines.append(
        f"- Residual (with active controls): "
        f"{_fmt_prob(result.residual_probability.top_event_probability)} "
        f"({result.residual_probability.method})"
    )
    for w in [*result.baseline_probability.warnings, *result.residual_probability.warnings, *result.warnings]:
        lines.append(f"  - warning: {w}")
    lines.append("")

    if result.controls:
        lines.append("## Controls")
        lines.append("")
        for c in result.controls:
            status = "active" if c.active else "inactive"
            lines.append(
                f"- {c.description} -> targets `{c.target_basic_event_id}`, "
                f"{c.effectiveness:.0%} effective ({status})"
            )
        lines.append("")

    lines.append("## Minimal Cut Sets")
    lines.append("")
    lines.append("| Events | Baseline P | Residual P |")
    lines.append("|---|---|---|")
    for cs in result.minimal_cut_sets:
        events = ", ".join(cs.event_descriptions)
        lines.append(
            f"| {events} | {_fmt_prob(cs.baseline_probability)} | {_fmt_prob(cs.residual_probability)} |"
        )
    lines.append("")

    if result.risk_quantification:
        rq = result.risk_quantification
        lines.append("## Risk Quantification (FAIR-lite)")
        lines.append("")
        lines.append(
            f"- Loss magnitude: {rq.loss_magnitude.amount:,.2f} {rq.loss_magnitude.currency} "
            f"({rq.loss_magnitude.time_base})"
        )
        lines.append(f"- Baseline ALE: {_fmt_money(rq.baseline_ale, rq.loss_magnitude.currency)}")
        lines.append(f"- Residual ALE: {_fmt_money(rq.residual_ale, rq.loss_magnitude.currency)}")
        lines.append(
            f"- Savings from active controls: {_fmt_money(rq.savings, rq.loss_magnitude.currency)}"
        )
        lines.append("")

    return "\n".join(lines)
